// حروف عربی که ظاهرشون با معادل فارسی یکیه ولی کد یونیکدشون فرق داره -- باعث می‌شه
// اسلاگ فارسی که با یه کیبورد/IME تایپ شده، با همون اسلاگ که با کیبورد دیگه‌ای تایپ شده
// (مثلاً توی نوار آدرس مرورگر) در دیتابیس یکی در نظر گرفته نشه.
// «ي» عربی (U+064A) -> «ی» فارسی (U+06CC)
// «ك» عربی (U+0643) -> «ک» فارسی (U+06A9)
export function normalizeSlug(input: string): string {
  return input
    .trim()
    .normalize("NFC")
    .replace(/\u064A/g, "\u06CC") // ي -> ی
    .replace(/\u0643/g, "\u06A9"); // ك -> ک
}
